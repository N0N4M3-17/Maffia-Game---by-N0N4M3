const { test, expect } = require('@playwright/test');
const fs = require('node:fs');

async function actor(playwright, prefix) {
  const api = await playwright.request.newContext({ baseURL: 'http://127.0.0.1:3028' });
  const username = `${prefix}${Date.now()}${Math.floor(Math.random() * 1000)}`;
  const response = await api.post('/api/auth/register', { data: { username, email: `${username}@example.test`, password: 'test-only-password' } });
  expect(response.status()).toBe(201);
  const { account } = await response.json();
  return { api, account };
}
async function post(api, path, data = {}) {
  const response = await api.post(path, { data });
  expect(response.ok(), `${path}: ${await response.text()}`).toBeTruthy();
  return response.json();
}

test('real room lifecycle, observer modes, host scope, timeout, eviction, and in-game void', async ({ playwright }) => {
  const host = await actor(playwright, 'host');
  const stranger = await actor(playwright, 'stranger');
  const player = await actor(playwright, 'member');
  const other = await actor(playwright, 'other');
  const admin = await playwright.request.newContext({ baseURL: 'http://127.0.0.1:3028' });
  await post(admin, '/api/auth/login', { login: 'n0n4m3-admin', password: 'admin123' });
  const { room } = await post(host.api, '/api/rooms', { name: 'Moderation integration table', networkMode: 'local' });
  const join = `/api/rooms/${room.id}/join`;
  const moderate = `/api/rooms/${room.id}/moderate`;
  expect((await stranger.api.patch(`/api/rooms/${room.id}`, { data: { name: 'Stolen', networkMode: 'local' } })).status()).toBe(403);
  expect((await stranger.api.delete(`/api/rooms/${room.id}`)).status()).toBe(403);
  expect((await stranger.api.post(join, { data: { mode: 'observer' } })).status()).toBe(403);
  await post(host.api, join, { mode: 'observer' });
  await post(admin, join, { mode: 'observer' });
  expect((await (await admin.get('/api/gm-state')).json()).playerCount).toBe(0);
  await post(admin, join, { mode: 'player' });
  expect((await (await admin.get('/api/gm-state')).json()).viewerMode).toBe('player');
  await post(admin, join, { mode: 'observer' });
  const { playerId } = await post(player.api, join, { mode: 'player' });
  const listed = (await (await host.api.get('/api/rooms')).json()).rooms.find((item) => item.id === room.id);
  expect(listed.canManage).toBeTruthy();
  expect(listed.members.filter((item) => item.mode === 'observer')).toHaveLength(2);
  const publicRoom = (await (await stranger.api.get('/api/rooms')).json()).rooms.find((item) => item.id === room.id);
  expect(publicRoom.members).toBeUndefined();
  expect(publicRoom.restrictions).toBeUndefined();
  const { account: adminAccount } = await (await admin.get('/api/me')).json();
  expect((await host.api.post(moderate, { data: { action: 'kick', accountId: adminAccount.id } })).status()).toBe(403);
  expect((await host.api.post(moderate, { data: { action: 'timeout', accountId: player.account.id, durationSec: 1 } })).status()).toBe(400);
  await post(host.api, moderate, { action: 'timeout', accountId: player.account.id, durationSec: 300 });
  expect((await player.api.post(join, { data: { mode: 'player' } })).status()).toBe(403);
  expect((await player.api.post('/api/join', { data: {} })).status()).toBe(403);
  const persisted = JSON.parse(fs.readFileSync('.local-backups/ui-preview-runtime/data/mafia-db.json', 'utf8'));
  expect(persisted.rooms.find((item) => item.id === room.id).blockedUntil[player.account.id]).toBeGreaterThan(Date.now());
  await post(host.api, moderate, { action: 'unban', accountId: player.account.id });
  await post(player.api, join, { mode: 'player' });
  expect((await host.api.post(moderate, { data: { action: 'evict', accountId: player.account.id } })).status()).toBe(403);
  await post(admin, moderate, { action: 'evict', accountId: player.account.id });
  expect((await player.api.post(join, { data: { mode: 'player' } })).status()).toBe(403);
  expect((await host.api.post(moderate, { data: { action: 'unban', accountId: player.account.id } })).status()).toBe(403);
  await post(admin, moderate, { action: 'unban', accountId: player.account.id });
  await post(player.api, join, { mode: 'player' });
  await post(host.api, moderate, { action: 'kick', accountId: player.account.id });
  await post(player.api, join, { mode: 'player' });
  await post(stranger.api, join, { mode: 'player' });
  await post(other.api, join, { mode: 'player' });
  const spare = await post(stranger.api, '/api/rooms', { name: 'Reserved room', networkMode: 'local' });
  expect((await (await host.api.get('/api/gm-state')).json()).room.id).toBe(room.id);
  expect((await host.api.delete(`/api/rooms/${spare.room.id}`)).status()).toBe(403);
  expect((await stranger.api.delete(`/api/rooms/${spare.room.id}`)).ok()).toBeTruthy();
  expect((await (await host.api.get('/api/gm-state')).json()).playerCount).toBe(3);
  await post(host.api, '/api/gm/config', { mafia: 1, sheriff: 1, doctor: 0, vigilante: 0, jester: 0, town: 1, vigilanteShots: 1 });
  await post(host.api, '/api/gm/start');
  await post(host.api, moderate, { action: 'kick', accountId: player.account.id });
  const outcome = await (await admin.get('/api/gm-state')).json();
  expect(outcome.phase).toBe('game_over'); expect(outcome.winner).toBe('Voided');
  expect(outcome.playerChat.some((line) => line.message.includes('removed from the room'))).toBeTruthy();
  expect((await (await player.api.get('/api/my-player')).json()).joined).toBeFalsy();
  expect((await (await player.api.get('/api/me')).json()).account.scores.games).toBe(0);
  await post(host.api, '/api/gm/return-lobby');
  await post(player.api, join, { mode: 'player' });
  await post(host.api, '/api/gm/start');
  expect((await host.api.delete(`/api/rooms/${room.id}`)).ok()).toBeTruthy();
  const disbanded = await (await admin.get('/api/gm-state')).json();
  expect(disbanded.phase).toBe('game_over'); expect(disbanded.voidReason).toContain('disbanded');
  expect((await player.api.post(join, { data: { mode: 'player' } })).status()).toBe(404);
  await post(admin, '/api/gm/return-lobby');
  expect((await (await admin.get('/api/gm-state')).json()).playerCount).toBe(0);
  expect((await (await admin.get('/api/rooms')).json()).rooms.some((item) => item.id === room.id)).toBeFalsy();
  for (const item of [host, stranger, player, other]) await item.api.dispose();
  await admin.dispose();
});

test('admin manages room details and observes without creating a player seat in portrait UI', async ({ page, playwright }) => {
  await page.request.post('/api/auth/login', { data: { login: 'n0n4m3-admin', password: 'admin123' } });
  const created = await (await page.request.post('/api/rooms', { data: { name: 'Portrait management', networkMode: 'local' } })).json();
  const member = await actor(playwright, 'portrait');
  await post(member.api, `/api/rooms/${created.room.id}/join`, { mode: 'player' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await page.locator(`[data-room-join="${created.room.id}"][data-room-mode="observer"]`).click();
  await expect(page.locator('#tab-host')).toHaveClass(/active/);
  expect((await (await page.request.get('/api/gm-state')).json()).playerCount).toBe(1);
  await page.locator('[data-tab="rooms"]').click();
  await page.locator(`[data-room-manage="${created.room.id}"]`).click();
  await expect(page.locator('#room-manager-dialog')).toBeVisible();
  await page.locator('#room-details-form input[name="name"]').fill('Renamed portrait room');
  await page.locator('#room-details-form button').click();
  await expect(page.locator('#room-manager-title')).toHaveText('Renamed portrait room');
  await page.locator(`[data-moderate="timeout"][data-account="${member.account.id}"]`).click();
  await page.locator('#confirm-dialog [value="confirm"]').click();
  await expect(page.locator('.room-restrictions')).toContainText(member.account.displayName);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
  await page.screenshot({ path: 'artifacts/screenshots/room-management-portrait.png', fullPage: true });
  await page.locator('[data-moderate="unban"]').click();
  await page.locator('#confirm-dialog [value="confirm"]').click();
  await expect(page.locator('.room-restrictions')).toContainText('No active restrictions');
  await page.locator('#disband-room').click();
  await page.locator('#confirm-dialog [value="confirm"]').click();
  await expect(page.locator('#room-manager-dialog')).toBeHidden();
  await member.api.dispose();
});
